const languages = { en, fr, de, it, es };
const lang = (navigator.languages || [navigator.language || 'en']).map((l) => l.slice(0, 2)).find((l) => languages[l]) || 'en';
const strings = languages[lang];

export function t(key, ...args) {
  const s = strings[key] ?? en[key] ?? key;
  return s.replace(/\{(\d)\}/g, (_, i) => args[i] ?? '');
}

export function applyTranslations() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const s = t(el.dataset.i18n);
    if (/[<]/.test(s)) el.innerHTML = s;
    else el.textContent = s;
  }
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
}
